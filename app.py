@app.get("/")
def health_check():
    return {"status": "Active", "model": "LogisticRegression"}


@app.post("/predict")
def predict_heart_disease(patient: PatientFeatures):
    # Convert input object to numpy array matching feature shape (1, 13)
    data_values = [
        patient.age,
        patient.sex,
        patient.cp,
        patient.trestbps,
        patient.chol,
        patient.fbs,
        patient.restecg,
        patient.thalach,
        patient.exang,
        patient.oldpeak,
        patient.slope,
        patient.ca,
        patient.thal,
    ]

    input_array = np.asarray(data_values).reshape(1, -1)

    # Make prediction & obtain risk probability
    prediction = int(model.predict(input_array)[0])
    probability = float(model.predict_proba(input_array)[0][1])

    return {
        "prediction": prediction,
        "result": (
            "Defective Heart (Disease Detected)"
            if prediction == 1
            else "Healthy Heart"
        ),
        "disease_probability": round(probability, 4),
    }


